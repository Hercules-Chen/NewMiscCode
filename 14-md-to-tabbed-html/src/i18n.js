export function messages(lang) { return M[lang] || M['zh-TW']; }

/** 產生頁面的 UI 字串，依頁面 lang。 */
export function pageStrings(lang) {
  const en = String(lang).toLowerCase().startsWith('en');
  return en
    ? { showAll: 'Show all', theme: 'Theme', themeTitle: 'Toggle theme: auto / light / dark', tabs: 'Sections', contents: 'On this tab', docs: 'Documents', generated: 'Generated by md2tabs',
        adm: { note: 'Note', tip: 'Tip', important: 'Important', warning: 'Warning', caution: 'Caution' } }
    : { showAll: '全部顯示', theme: '主題', themeTitle: '切換主題：自動 / 淺色 / 深色', tabs: '分頁', contents: '本頁目錄', docs: '文件清單', generated: '由 md2tabs 產生',
        adm: { note: '備註', tip: '提示', important: '重要', warning: '警告', caution: '小心' } };
}
