// Build: copy DuckDB-WASM / SheetJS runtime files into public/vendor/, bundle duckdb-browser.mjs
// (+ apache-arrow) into one IIFE, generate sample data, and produce dist/artifact.html
// (a single self-contained HTML that loads the .wasm/worker from jsDelivr).
//
// Usage: node scripts/build.mjs [--no-vendor] [--no-artifact]
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PUB = path.join(ROOT, 'public');
const VENDOR = path.join(PUB, 'vendor');
const DIST = path.join(ROOT, 'dist');
const args = new Set(process.argv.slice(2));
const require = createRequire(import.meta.url);

function log(...a) { console.log('[build]', ...a); }

async function readJson(p) { return JSON.parse(await fs.readFile(p, 'utf8')); }

async function main() {
  const ddbPkgDir = path.join(ROOT, 'node_modules', '@duckdb', 'duckdb-wasm');
  const ddbPkg = await readJson(path.join(ddbPkgDir, 'package.json'));
  const xlsxPkg = await readJson(path.join(ROOT, 'node_modules', 'xlsx', 'package.json'));
  const DDB_VERSION = ddbPkg.version;
  const XLSX_VERSION = xlsxPkg.version;
  log('duckdb-wasm', DDB_VERSION, '| xlsx', XLSX_VERSION);

  // keep the app default in sync with the installed version
  const appSrc = await fs.readFile(path.join(PUB, 'js', 'app.js'), 'utf8');
  if (!appSrc.includes(`duckdbVersion: '${DDB_VERSION}'`)) {
    throw new Error(`public/js/app.js default duckdbVersion does not match installed ${DDB_VERSION}`);
  }

  // 1) bundle duckdb-browser.mjs + apache-arrow -> IIFE global `duckdb`
  const esbuild = require('esbuild');
  const bundle = await esbuild.build({
    entryPoints: [path.join(ddbPkgDir, 'dist', 'duckdb-browser.mjs')],
    bundle: true,
    format: 'iife',
    globalName: 'duckdb',
    platform: 'browser',
    target: ['chrome100', 'firefox100', 'safari15'],
    minify: true,
    write: false,
    legalComments: 'none',
    banner: { js: `/* @duckdb/duckdb-wasm ${DDB_VERSION} (MIT) + apache-arrow (Apache-2.0), bundled by scripts/build.mjs */` }
  });
  const bundleJs = bundle.outputFiles[0].text;

  // 2) vendor files for the local / static-host variant
  if (!args.has('--no-vendor')) {
    await fs.mkdir(VENDOR, { recursive: true });
    await fs.writeFile(path.join(VENDOR, 'duckdb.iife.js'), bundleJs);
    const files = ['duckdb-mvp.wasm', 'duckdb-eh.wasm', 'duckdb-browser-mvp.worker.js', 'duckdb-browser-eh.worker.js'];
    for (const f of files) {
      await fs.copyFile(path.join(ddbPkgDir, 'dist', f), path.join(VENDOR, f));
    }
    await fs.copyFile(path.join(ROOT, 'node_modules', 'xlsx', 'dist', 'xlsx.full.min.js'), path.join(VENDOR, 'xlsx.full.min.js'));
    await fs.writeFile(path.join(VENDOR, 'VERSIONS.txt'), `duckdb-wasm ${DDB_VERSION}\nxlsx ${XLSX_VERSION}\nbuilt ${new Date().toISOString()}\n`);
    for (const f of await fs.readdir(VENDOR)) {
      const st = await fs.stat(path.join(VENDOR, f));
      log('vendor/' + f, (st.size / 1048576).toFixed(2) + ' MB');
    }
  }

  // 3) sample data (deterministic)
  await import(pathToFileURL(path.join(PUB, 'js', 'samplegen.js')).href);
  const SampleGen = globalThis.SampleGen;
  await fs.mkdir(path.join(PUB, 'sample'), { recursive: true });
  await fs.writeFile(path.join(PUB, 'sample', 'app-log.jsonl'), SampleGen.generateLogJsonl());
  await fs.writeFile(path.join(PUB, 'sample', 'sales.csv'), SampleGen.generateSalesCsv());
  log('sample/app-log.jsonl, sample/sales.csv written');

  // 4) dist/artifact.html: inline CSS + all scripts, CDN mode for wasm/worker
  if (!args.has('--no-artifact')) {
    let html = await fs.readFile(path.join(PUB, 'index.html'), 'utf8');
    const esc = (js) => js.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');
    const css = await fs.readFile(path.join(PUB, 'css', 'app.css'), 'utf8');
    html = html.replace(/<link rel="stylesheet" href="css\/app\.css">/, () => `<style>\n${css}</style>`);
    const scriptRe = /<script src="([^"]+)"><\/script>/g;
    const srcs = [...html.matchAll(scriptRe)].map((m) => m[1]);
    const contents = {};
    for (const s of srcs) {
      contents[s] = s === 'vendor/duckdb.iife.js' ? bundleJs : await fs.readFile(path.join(PUB, s), 'utf8');
    }
    const cfg = `window.DDB_CONFIG = ${JSON.stringify({ mode: 'cdn', duckdbVersion: DDB_VERSION, xlsxVersion: XLSX_VERSION })};`;
    let first = true;
    html = html.replace(scriptRe, (m, s) => {
      const pre = first ? `<script>\n${cfg}\n</script>\n` : '';
      first = false;
      return `${pre}<script>\n/* ---- ${s} ---- */\n${esc(contents[s])}\n</script>`;
    });
    html = html.replace('<meta charset="utf-8">', `<meta charset="utf-8">\n<!-- Generated by scripts/build.mjs from public/index.html - do not edit. duckdb-wasm ${DDB_VERSION} wasm+worker from https://cdn.jsdelivr.net/npm/@duckdb/duckdb-wasm@${DDB_VERSION}/dist/ -->`);
    await fs.mkdir(DIST, { recursive: true });
    await fs.writeFile(path.join(DIST, 'artifact.html'), html);
    log('dist/artifact.html', (Buffer.byteLength(html) / 1024).toFixed(0) + ' KB');
  }
  log('done');
}

main().catch((e) => { console.error('[build] FAILED', e); process.exit(1); });
