// gentestdata writes the deliberately broken sample corpus into testdata/.
// The bytes are generated (not hand-edited) so they are exact and reproducible:
//
//	go run ./cmd/gentestdata [-out testdata]
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"golang.org/x/text/encoding/japanese"
	"golang.org/x/text/encoding/simplifiedchinese"
	"golang.org/x/text/encoding/traditionalchinese"
	"golang.org/x/text/encoding/unicode"
)

const tradText = "編碼醫生測試檔案\n這是一個使用 Big5（CP950）編碼的繁體中文文字檔。\n設定檔案已經儲存完成，請確認畫面上的中文是否正確顯示。\n如果看到亂碼，代表程式用錯誤的編碼讀取了這個檔案。\n"

const simpText = "编码医生测试文件\n这是一个使用 GBK 编码的简体中文文本文件。\n设置已经保存完成，请确认显示是否正确。\n"

const jaText = "エンコーディングのテストです。\nこれは Shift_JIS で保存された日本語のファイルです。\n文字化けしていないか確認してください。\n"

// MojibakeSource is the original text used for the mojibake samples (also used by tests).
const mojiSource = "編碼醫生：這段文字原本是 UTF-8，請確認是否能正確還原。\n設定檔案已經儲存完成。\n"

func must(b []byte, err error) []byte {
	if err != nil {
		panic(err)
	}
	return b
}

func crlf(s string) string { return strings.ReplaceAll(s, "\n", "\r\n") }

func big5(s string) []byte { return must(traditionalchinese.Big5.NewEncoder().Bytes([]byte(s))) }

func cp1252Mojibake(s string) string {
	// decode UTF-8 bytes as windows-1252 (lossless table incl. C1 slots)
	high := []rune{0x20AC, 0x81, 0x201A, 0x192, 0x201E, 0x2026, 0x2020, 0x2021, 0x2C6, 0x2030, 0x160, 0x2039, 0x152, 0x8D, 0x17D, 0x8F,
		0x90, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2013, 0x2014, 0x2DC, 0x2122, 0x161, 0x203A, 0x153, 0x9D, 0x17E, 0x178}
	var sb strings.Builder
	for _, c := range []byte(s) {
		if c >= 0x80 && c < 0xA0 {
			sb.WriteRune(high[c-0x80])
		} else {
			sb.WriteRune(rune(c))
		}
	}
	return sb.String()
}

func main() {
	out := flag.String("out", "testdata", "output folder")
	flag.Parse()
	files := map[string][]byte{
		// legacy encodings
		"big5-notes.txt":     big5(crlf(tradText)),
		"big5-readme.md":     big5(crlf("# 說明文件\n\n" + tradText)),
		"gbk-simplified.txt": must(simplifiedchinese.GBK.NewEncoder().Bytes([]byte(crlf(simpText)))),
		"sjis-japanese.txt":  must(japanese.ShiftJIS.NewEncoder().Bytes([]byte(crlf(jaText)))),
		"utf16le-bom.txt":    must(unicode.UTF16(unicode.LittleEndian, unicode.UseBOM).NewEncoder().Bytes([]byte(crlf("UTF-16LE 檔案（Windows 記事本的「Unicode」）\n第二行\n")))),
		// BOM policy
		"bom-readme.md": append([]byte{0xEF, 0xBB, 0xBF}, []byte("# 有 BOM 的 Markdown\n\n應該是 UTF-8 無 BOM。\n")...),
		"good.md":       []byte("# 正常的 Markdown\n\nUTF-8 無 BOM，LF 換行。\n"),
		"good.json":     []byte("{\n  \"name\": \"編碼醫生\",\n  \"ok\": true\n}\n"),
		// batch files
		"chinese-echo.bat": []byte("@echo off\nrem 這是中文註解\necho 開始執行...\npause\n"),
		"good.bat":         []byte(crlf("@echo off\npushd \"%~dp0\"\necho [good.bat] folder: %CD%\npopd\n")),
		"bom.cmd":          append([]byte{0xEF, 0xBB, 0xBF}, []byte(crlf("@echo off\necho hello\n"))...),
		// PowerShell
		"no-bom.ps1":     []byte(crlf("# 沒有 BOM 的 PowerShell 腳本\nWrite-Host \"你好，世界\"\n")),
		"big5-ansi.ps1":  big5(crlf("# 用記事本 ANSI 存檔的腳本\nWrite-Host \"設定完成\"\n")),
		"good.ps1":       append([]byte{0xEF, 0xBB, 0xBF}, []byte(crlf("# 正確：UTF-8 with BOM\nWrite-Host \"完成\"\n"))...),
		"ascii-only.ps1": []byte(crlf("Write-Host \"ascii only, no BOM needed\"\n")),
		// line endings
		"mixed-eol.js": []byte("// mixed line endings\r\nconst a = 1;\nconst b = 2;\r\nconsole.log('混合換行', a + b);\n"),
		"crlf.sh":      []byte("#!/bin/sh\r\necho hello\r\n"),
		// mojibake
		"mojibake-latin1.md": []byte(cp1252Mojibake(mojiSource)),
		"mojibake-cp950.txt": must(traditionalchinese.Big5.NewDecoder().Bytes([]byte(mojiSource))),
		"lost-fffd.txt":      []byte(strings.ToValidUTF8(string(big5(tradText)), "\uFFFD")),
		// NUL bytes
		"nul-bytes.txt": []byte("text with a stray NUL\x00 byte in the middle\n"),
	}
	if err := os.MkdirAll(*out, 0o755); err != nil {
		panic(err)
	}
	for name, b := range files {
		if err := os.WriteFile(filepath.Join(*out, name), b, 0o644); err != nil {
			panic(err)
		}
	}
	readme := "testdata: deliberately broken sample files generated by `go run ./cmd/gentestdata`.\r\n" +
		"Do not edit by hand. These files intentionally violate the encoding rules.\r\n"
	_ = os.WriteFile(filepath.Join(*out, "README.txt"), []byte(readme), 0o644)
	fmt.Printf("wrote %d files to %s\n", len(files)+1, *out)
}
